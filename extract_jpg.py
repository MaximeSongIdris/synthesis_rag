import torch
from pathlib import Path
from collections.abc import Iterable
from PIL import Image
from transformers import AutoProcessor, AutoModelForImageTextToText
from docling_core.types.doc import (
    DoclingDocument, DocItemLabel, ImageRef, ImageRefMode,
    ProvenanceItem, BoundingBox, Size, CoordOrigin,
)


class Jpg2DoclingDocument:
    """Turn a jpg photo into a one-page DoclingDocument whose picture is captioned by a VLM.

    Why we build the DoclingDocument ourselves instead of using Docling's DocumentConverter:
    when we fed jpg files to Docling's image pipeline, it did not reliably detect the photo
    as a picture item, so there was no picture to caption or describe. Our working hypothesis
    is that its layout model is designed for document pages (text, tables, figures) and does
    not treat a whole photograph as a figure; we did not confirm this.

    Since the output must still be in the same DoclingDocument format as the other file types,
    we build it directly:
      - one page, sized like the image;
      - one picture covering that whole page (provenance = full-page bounding box);
      - one caption, generated by a VLM (transformers), linked to the picture.
    """

    DEFAULT_PROMPT = ("Décris cette photographie en français, en 2 à 4 phrases : "
                      "personnes, objets, lieu, ambiance. N'invente rien.")

    def __init__(
        self,
        vlm_model: str | Path,
        prompt: str | None = None,
        max_side: int = 1280,
        max_new_tokens: int = 200,
    ) -> None:
        self.device = "cuda" if torch.cuda.is_available() else "cpu"
        self.processor = AutoProcessor.from_pretrained(vlm_model)
        self.model = AutoModelForImageTextToText.from_pretrained(vlm_model).to(self.device)
        self.prompt = prompt or self.DEFAULT_PROMPT
        self.max_side = max_side
        self.max_new_tokens = max_new_tokens

    def describe(self, img: Image.Image) -> str:
        input_img = img.copy()
        input_img.thumbnail((self.max_side, self.max_side))  # limit img size
        chat = [{"role": "user", "content": [{"type": "image"}, {"type": "text", "text": self.prompt}]}]
        text = self.processor.apply_chat_template(chat, add_generation_prompt=True)
        inputs = self.processor(images=input_img, text=text, return_tensors="pt").to(self.device)
        with torch.no_grad():
            out = self.model.generate(**inputs, max_new_tokens=self.max_new_tokens)
        new_tokens = out[0][inputs["input_ids"].shape[1]:]
        return self.processor.decode(new_tokens, skip_special_tokens=True).strip()

    def convert(self, path: str | Path) -> DoclingDocument:
        path = Path(path)
        img = Image.open(path).convert("RGB")
        w, h = img.size

        doc = DoclingDocument(name=path.stem)
        doc.add_page(page_no=1, size=Size(width=w, height=h))  # empty page with img size
        caption = doc.add_text(label=DocItemLabel.CAPTION, text=self.describe(img))  # add caption
        doc.add_picture(
            image=ImageRef.from_pil(img, dpi=72),
            caption=caption,
            prov=ProvenanceItem(
                page_no=1, charspan=(0, 0),
                bbox=BoundingBox(l=0, t=0, r=w, b=h, coord_origin=CoordOrigin.TOPLEFT),
            ),
        )  # add img with reference to caption
        return doc

    def convert_all(self, paths: Iterable[str | Path], out_dir: str | Path) -> None:
        out_dir = Path(out_dir)
        out_dir.mkdir(parents=True, exist_ok=True)

        for path in map(Path, paths):
            doc = self.convert(path)
            doc.save_as_json(out_dir / f"{path.stem}.json", image_mode=ImageRefMode.REFERENCED)
            doc.save_as_markdown(out_dir / f"{path.stem}.md", image_mode=ImageRefMode.REFERENCED)
            print("SAVED:", path.name)